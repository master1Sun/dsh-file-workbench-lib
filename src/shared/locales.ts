/** {placeholder} 插值替换。 */
export function interpolate(text: string | undefined, params?: Record<string, string | number>): string {
  if (text === undefined) return "";
  if (!params) return text;
  return text.replace(/\{([^}]+)\}/g, (_, k: string) => (params[k] !== undefined ? String(params[k]) : `{${k}}`));
}

/** 按语言取词（非 zh 回退 en）。 */
export function lookup(locale: string, key: CopyKey): string {
  const dict = locale.toLowerCase().startsWith("zh") ? zh : en;
  return dict[key] ?? en[key];
}